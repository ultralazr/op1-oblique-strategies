#!/usr/bin/env python3
"""Generate obl_data.c: stroke font (from the stock opfont.svg) + pre-wrapped card layouts.

usage: gen_data.py <opfont.svg> <cards.txt> <out.c> [--preview out.png]
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svgfont

ROWS = [-142.4, -57.4, 27.6, 112.7, 197.7, 282.8]
CELL = 56.7          # glyph cell height in font units
Q = 0.5              # stored coordinate = font units * Q (cell height -> 28)

# layout in screen pixels (320 x 160)
W, H = 320, 160
TEXT_H = 9.0         # glyph height in px
GAP = 3.0            # extra px between glyphs
SPACE = 6.0          # px advance for ' '
LINE = 16.0          # px between baselines
MAX_W = 292.0        # wrap width
TITLE = 'oblique strategies'
TITLE_H = 6.0
TITLE_Y = 9.0        # top of title glyphs
BODY_TOP, BODY_BOT = 26.0, 152.0

# hand-drawn glyphs missing from opfont (font units, cell 0..56.7 high)
EXTRA = {
    "'": [[(0.0, 0.0), (0.0, 14.2)]],
    '(': [[(11.0, 0.0), (3.0, 10.0), (0.0, 28.35), (3.0, 46.7), (11.0, 56.7)]],
    ')': [[(0.0, 0.0), (8.0, 10.0), (11.0, 28.35), (8.0, 46.7), (0.0, 56.7)]],
}


def load_font(svg):
    g = svgfont.load(svg)
    font = {}
    for ch, polys in g.items():
        if ch.isupper():
            continue
        pts = [p for poly in polys for p in poly]
        if not pts:
            continue
        x0 = min(p[0] for p in pts)
        top = max(r for r in ROWS if r <= min(p[1] for p in pts) + 1.0)
        font[ch] = [[(x - x0, y - top) for x, y in poly] for poly in polys]
    font.update(EXTRA)
    return font


def width_units(polys):
    return max(x for poly in polys for x, _ in poly)


def adv_px(font, ch, h):
    if ch == ' ':
        return SPACE * h / TEXT_H
    return width_units(font[ch]) * h / CELL + GAP * h / TEXT_H


def text_px(font, s, h):
    return sum(adv_px(font, c, h) for c in s) - (GAP * h / TEXT_H if s else 0)


def normalize(s, font):
    s = s.lower().replace('`', "'").replace('[', '(').replace(']', ')')
    return ''.join(c for c in s if c == ' ' or c in font)


def wrap(font, s):
    lines, cur = [], ''
    for w in s.split():
        t = (cur + ' ' + w) if cur else w
        if text_px(font, t, TEXT_H) <= MAX_W or not cur:
            cur = t
        else:
            lines.append(cur); cur = w
    if cur:
        lines.append(cur)
    return lines


def layout(font, s):
    """-> [(x_px, top_px, text)] centred block"""
    lines = wrap(font, normalize(s, font))
    total = (len(lines) - 1) * LINE + TEXT_H
    top = BODY_TOP + (BODY_BOT - BODY_TOP - total) / 2
    out = []
    for i, ln in enumerate(lines):
        out.append(((W - text_px(font, ln, TEXT_H)) / 2, top + i * LINE, ln))
    return out


def emit(font, cards, out):
    chars = sorted(font)
    strokes, gofs, gw = bytearray(), {}, {}
    for ch in chars:
        gofs[ch] = len(strokes)
        gw[ch] = round(width_units(font[ch]) * Q)
        for poly in font[ch]:
            pts = [(round(x * Q), round(y * Q)) for x, y in poly]
            pts = [p for k, p in enumerate(pts) if k == 0 or p != pts[k - 1]]
            if len(pts) < 2:
                pts = pts * 2
            for i in range(0, len(pts) - 1, 254):
                seg = pts[i:i + 255]
                strokes.append(len(seg))
                for x, y in seg:
                    assert 0 <= x < 256 and 0 <= y < 256, (ch, x, y)
                    strokes += bytes((x, y))
        strokes.append(0)
    L = ['/* generated by gen_data.py - do not edit */', '#include "obl.h"', '']
    L.append('const unsigned char obl_strokes[%d] = {' % len(strokes))
    for i in range(0, len(strokes), 24):
        L.append('  ' + ','.join(str(b) for b in strokes[i:i + 24]) + ',')
    L.append('};')
    L.append('const unsigned short obl_glyph_ofs[128] = {')
    L.append('  ' + ','.join(str(gofs.get(chr(c), 0xffff)) for c in range(128)) + '};')
    L.append('const unsigned char obl_glyph_w[128] = {')
    L.append('  ' + ','.join(str(gw.get(chr(c), 0)) for c in range(128)) + '};')
    # cards: per line x (px*16), top (px*16), text
    lines_c, idx = [], []
    for s in cards:
        lay = layout(font, s)
        idx.append(len(lines_c))
        for x, y, t in lay:
            lines_c.append((round(x * 16), round(y * 16), t))
    idx.append(len(lines_c))
    L.append('const obl_line_t obl_lines[%d] = {' % len(lines_c))
    for x, y, t in lines_c:
        L.append('  {%d, %d, "%s"},' % (x, y, t.replace('\\', '\\\\').replace('"', '\\"')))
    L.append('};')
    L.append('const unsigned short obl_card_first[%d] = {%s};' % (len(idx), ','.join(map(str, idx))))
    L.append('const int obl_ncards = %d;' % len(cards))
    tx = (W - text_px(font, TITLE, TITLE_H)) / 2
    L.append('const obl_line_t obl_title = {%d, %d, "%s"};' % (round(tx * 16), round(TITLE_Y * 16), TITLE))
    L.append('const int obl_scale_body = %d;   /* fixed .10 px per stored unit */' % round(TEXT_H / (CELL * Q) * 1024))
    L.append('const int obl_scale_title = %d;' % round(TITLE_H / (CELL * Q) * 1024))
    L.append('const int obl_gap_body = %d;' % round(GAP * 1024))
    L.append('const int obl_gap_title = %d;' % round(GAP * TITLE_H / TEXT_H * 1024))
    L.append('const int obl_space_body = %d;' % round(SPACE * 1024))
    L.append('const int obl_space_title = %d;' % round(SPACE * TITLE_H / TEXT_H * 1024))
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    return lines_c, idx


def preview(font, cards, png, which):
    from PIL import Image, ImageDraw
    S = 3
    img = Image.new('RGB', (W * S, H * S * len(which)), 'black')
    d = ImageDraw.Draw(img)
    for row, ci in enumerate(which):
        oy = row * H * S
        d.rectangle([2, oy + 2, W * S - 3, oy + H * S - 3], outline=(111, 113, 115))
        def draw(x, top, s, h, col):
            for ch in s:
                if ch != ' ':
                    for poly in font[ch]:
                        d.line([((x + px * h / CELL) * S, oy + (top + py * h / CELL) * S) for px, py in poly],
                               fill=col, width=2)
                x += adv_px(font, ch, h)
        draw((W - text_px(font, TITLE, TITLE_H)) / 2, TITLE_Y, TITLE, TITLE_H, (255, 58, 93))
        for x, y, t in layout(font, cards[ci]):
            draw(x, y, t, TEXT_H, (255, 255, 255))
    img.save(png)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('svg'); ap.add_argument('cards'); ap.add_argument('out')
    ap.add_argument('--preview')
    a = ap.parse_args()
    font = load_font(a.svg)
    cards = [l.strip() for l in open(a.cards, encoding='utf8') if l.strip()]
    lines_c, idx = emit(font, cards, a.out)
    nl = [idx[i + 1] - idx[i] for i in range(len(cards))]
    print(f'{len(cards)} cards, {len(lines_c)} lines, max {max(nl)} lines/card')
    if a.preview:
        longest = max(range(len(cards)), key=lambda i: len(cards[i]))
        preview(font, cards, a.preview, [0, 15, longest, 3])
